// Secondary compatibility safety net for legacy third-party/HTML fragments.
// Application UI uses useLang()/getT() directly; this opt-in-free fallback is
// intentionally kept only for content that cannot consume React context.
const domOriginals = new WeakMap();
const translatableAttributes = ['placeholder', 'title', 'aria-label', 'aria-description'];

function translateDomTextNode(node, lang) {
  const current = node.nodeValue || '';
  if (!current.trim()) return;

  const stored = domOriginals.get(node);
  const source = stored && current === stored.rendered ? stored.source : current;
  const leading = source.match(/^\s*/)?.[0] || '';
  const trailing = source.match(/\s*$/)?.[0] || '';
  const value = source.trim();
  const translated = translateDomValue(lang, value);

  domOriginals.set(node, { source: value, rendered: translated });
  const next = `${leading}${translated}${trailing}`;
  if (next !== current) node.nodeValue = next;
}

function translateDomElement(element, lang) {
  for (const attribute of translatableAttributes) {
    if (!element.hasAttribute(attribute)) continue;
    const current = element.getAttribute(attribute) || '';
    const key = `${attribute}:${current}`;
    const stored = domOriginals.get(element);
    const source = stored && stored[key] && current === stored[key].rendered
      ? stored[key].source
      : current;
    const translated = translateDomValue(lang, source);
    const values = stored || {};
    values[key] = { source, rendered: translated };
    domOriginals.set(element, values);
    if (translated !== current) element.setAttribute(attribute, translated);
  }
}

function translateDomValue(lang, value) {
  if (!value || value.length > 180) return value;
  for (const entry of Object.values(dict)) {
    const source = entry[0];
    if (source === value) return entry[LANG_INDEX[lang] ?? 0] || source;
    if (entry[1] === value) return entry[LANG_INDEX[lang] ?? 0] || source;
    if (entry[2] === value) return entry[LANG_INDEX[lang] ?? 0] || source;
  }
  return value;
}

export function syncDomTranslations(lang) {
  if (typeof document === 'undefined') return;
  const root = document.body;
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    const parent = node.parentElement;
    if (parent && !['SCRIPT', 'STYLE', 'NOSCRIPT'].includes(parent.tagName)) {
      translateDomTextNode(node, lang);
    }
    node = walker.nextNode();
  }
  document.querySelectorAll('*').forEach((element) => translateDomElement(element, lang));
}

export function observeDomTranslations(getLang) {
  if (typeof document === 'undefined') return () => {};
  const observer = new MutationObserver(() => {
    syncDomTranslations(getLang());
  });
  observer.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true });
  return () => observer.disconnect();
}

