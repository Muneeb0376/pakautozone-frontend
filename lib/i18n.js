const warned = new Set();

function interpolate(str, vars) {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
}

export function translate(lang, key, vars) {
  const safeLang = LANG_INDEX[lang] !== undefined ? lang : FALLBACK_LANG;
  const entry = dict[key];
  const idx = LANG_INDEX[safeLang] ?? LANG_INDEX[FALLBACK_LANG];

  if (!entry) {
    if (process.env.NODE_ENV !== 'production' && !warned.has(key)) {
      warned.add(key);
      console.warn(`[i18n] key maujood nahi: "${key}"`);
    }
    const last = String(key).split('.').pop();
    return last.replace(/([A-Z])/g, ' $1').replace(/^./, (c) => c.toUpperCase()).trim();
  }

  if (!entry[idx]) {
    const fallbackIdx = LANG_INDEX[FALLBACK_LANG] ?? 1;
    if (process.env.NODE_ENV !== 'production' && !warned.has(safeLang + key)) {
      warned.add(safeLang + key);
      console.warn(`[i18n] "${key}" ka tarjuma "${safeLang}" mein nahi hai`);
    }
    return interpolate(entry[fallbackIdx] || entry[0], vars);
  }

  return interpolate(entry[idx], vars);
}

export function useTranslation(lang) {
  return { t: (key, vars) => translate(lang, key, vars) };
}

export function translateApiError(error, t) {
  const message = (
    error?.response?.data?.message ||
    error?.response?.data?.error ||
    error?.message ||
    ''
  ).toString();

  const lowered = message.toLowerCase();

  if (lowered.includes('google id token is missing') || lowered.includes('google token')) return t('auth.errGoogleFailed');
  if (lowered.includes('invalid credentials') || lowered.includes('incorrect email') || lowered.includes('wrong password') || lowered.includes('email or password')) return t('api.invalidCredentials');
  if (lowered.includes('already registered') || lowered.includes('email already')) return t('auth.emailTaken');
  if (lowered.includes('not found')) return t('api.notFound');
  if (lowered.includes('unauthorized') || lowered.includes('token expired') || lowered.includes('session has expired') || lowered.includes('please log in')) return t('api.unauthorized');
  if (lowered.includes('forbidden') || lowered.includes('not allowed')) return t('api.forbidden');
  if (lowered.includes('timeout') || error?.code === 'ECONNABORTED') return t('api.timeout');
  if (error?.code === 'ERR_NETWORK' || lowered.includes('network') || lowered.includes('failed to fetch')) return t('api.network');
  if (error?.response?.status === 500 || lowered.includes('server error')) return t('api.serverError');
  if (error?.response?.status === 404) return t('api.notFound');
  if (error?.response?.status === 401) return t('api.unauthorized');
  if (error?.response?.status === 403) return t('api.forbidden');

  return t('common.somethingWrong');
}

